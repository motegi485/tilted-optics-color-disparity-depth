"""開口 A を軸にした、距離とぼけの試算（2026-11-06）。薄レンズ・実測なし。"""
import math

BETA = 4.0 / (3.0 * math.pi)
P_1080 = 109.3 / 5398.0  # mm/px
V = 90.2
F_1080 = V / P_1080
F_528 = F_1080 * 528.0 / 1080.0
HC = 1300.0
f = 90.0

print(f"F_1080={F_1080:.1f} F_528={F_528:.1f} beta={BETA:.4f}")

# 物体: 名前, 下端 H0, 上端 H1 [mm], 縦の大きさ
objects = [
    ("路面の標示(高さ0)", 0, 0),
    ("小さな落下物 0.2 m", 0, 200),
    ("コーン 0.7 m", 0, 700),
    ("子ども 1.2 m", 0, 1200),
    ("車 1.5 m", 0, 1500),
    ("人 1.7 m", 0, 1700),
    ("路側標識 0.6 m(1.8-2.4)", 1800, 2400),
    ("片持標識 0.9 m(5.0-5.9)", 5000, 5900),
    ("灯器 0.45 m(4.775-5.225)", 4775, 5225),
]
A = f / 5.6
print("\n--- ぼけ/物体の縦 [%] F5.6。距離によらない ---")
print("対象, 傾けない無限遠, 路面合焦(上端), 路面合焦(中央), 比(路面上端/無限遠)")
for name, h0, h1 in objects:
    h = h1 - h0
    if h == 0:
        print(f"{name}: 比を定義できない（路面合焦でぼけ0）")
        continue
    c0 = A / h * 100
    top = A / HC * h1 / h * 100
    mid = A / HC * (h0 + h1) / 2 / h * 100
    print(f"{name}: {c0:.2f} / {top:.2f} / {mid:.2f} / {top / c0:.2f}")

print("\n--- 開口 A ごとの距離精度とぼけ（f=90, 528 幅 F）---")
print("N, A[mm], K[px mm], z=10/20/30/50 の K/z[px], δd=0.15 の誤差 -/+ % (z=10,20,30,50), 人 c/h(0°) %, 路面立ち物 c/h(上端) %, 路側標識(上端)%, 片持(中央)%")
for N in [11, 8, 5.6, 4, 2.8, 2, 1.4]:
    A_ = f / N
    K = BETA * A_ * F_528
    row = []
    for z in [10000, 20000, 30000, 50000]:
        dz = K / z
        minus = 0.15 / (dz + 0.15) * 100
        plus = (0.15 / (dz - 0.15) * 100) if dz > 0.15 else float("inf")
        row.append(f"{dz:.2f}(-{minus:.0f}/+{plus:.0f})")
    print(
        f"F{N}: A={A_:.1f} K={K:.0f} "
        + " ".join(row)
        + f" | 人0° {A_ / 1700 * 100:.2f} 路面立ち {A_ / HC * 100:.2f} 路側 {A_ / HC * 2400 / 600 * 100:.1f} 片持 {A_ / HC * 5450 / 900 * 100:.1f}"
    )

print("\n--- 物体の像の大きさとぼけ px（528 幅 F, F5.6）---")
for z in [10, 15, 20, 30, 40, 50]:
    zmm = z * 1000
    per = F_528 * 1700 / zmm
    car = F_528 * 1500 / zmm
    c0 = A * F_528 / zmm
    print(f"z={z}m 人 {per:.0f}px 車高 {car:.0f}px 0°ぼけ {c0:.2f}px 路面の人頭 {c0 * 1700 / HC:.2f}px")

print("\n--- 縦画角と全身が入る距離 ---")
sensor_v = 720 * P_1080
vfov = 2 * math.degrees(math.atan(sensor_v / 2 / V))
print(f"縦画角 {vfov:.2f}°（720 行）")
t = math.tan(math.radians(vfov / 2))
print(f"水平カメラで足元(路面)が入る距離 {HC / t / 1000:.1f} m, 1.7 m の人の頭が入る距離 {(1700 - HC) / t / 1000:.1f} m")

print("\n--- Cityscapes との F の比（fx は記憶値、要確認）---")
print(f"2262.5/F_528 = {2262.5 / F_528:.3f}")
