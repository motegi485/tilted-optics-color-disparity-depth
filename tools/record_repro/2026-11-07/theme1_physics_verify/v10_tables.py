print("=== Michi 2012 §IV-C の 3 点 ===")
pts = [(308, 224.9), (260, 245.6), (170, 315.9)]
A_ = np.array([[1 / pts[0][0], 1], [1 / pts[2][0], 1]])
a, b = np.linalg.solve(A_, [pts[0][1], pts[2][1]])
print(f"z=a/y+b（報告書の形）: a={a:.0f}, b={b:.1f}, y=260 → {a/260+b:.1f} cm（実 245.6）")
