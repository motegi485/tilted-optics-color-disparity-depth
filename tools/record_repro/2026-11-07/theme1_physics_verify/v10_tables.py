print("平坦な地面の幾何は z=a/(y-u)（外側のオフセットなし）")
for (i, j, k) in [(0, 1, 2), (1, 2, 0), (0, 2, 1)]:
    (y1, z1), (y2, z2), (y3, z3) = pts[i], pts[j], pts[k]
    u = (z1 * y1 - z2 * y2) / (z1 - z2)
    aa = z1 * (y1 - u)
    print(f"  点 {y1},{y2} で決めると u={u:.1f}, a={aa:.0f}, y={y3} → {aa/(y3-u):.1f} cm（実 {z3}）")
